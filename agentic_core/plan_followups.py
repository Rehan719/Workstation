"""
Follow-up register — the tasks a round FINDS but does not DO, slotted into the delivery plan and scheduled.

Before this existed a found-but-deferred task lived in a chat chip, a "NOT DONE, and why" paragraph or a
commit message, and nothing made the next round pick it up. Now every such task is a row in
docs/FOLLOWUPS.json with a SLOT — the delivery-plan item whose round will do it (P1.13, P2.6, …), or OWNER
(it waits on an Owner decision and is never scheduled into a round). The schedule is DERIVED: the plan's own
item order, each open item carrying its rows. It is rendered between markers into the delivery plan
(docs/FABLE_DELIVERY_PROMPT.md) and the living plan (docs/WORKSTATION_IDBO_LIVING_PLAN.md §6.4), served at
GET /api/v1/plan/followups, and `check()` is enforced by test_w462_followup_register_is_scheduled_and_in_lockstep
and test_w469_the_plan_carries_every_followup_and_keeps_itself_current.

W469 (the Owner's instruction, 2026-09-17) — the plan keeps itself current:
  · NEXT is retired. It meant "its own round, before the next plan item", and because rounds register more
    than they close, the NEXT queue grew (25 → 42 rows) and held P1.13 back indefinitely. Every row now rides
    the plan item that owns its area, so found work lengthens that item instead of queueing in front of the plan.
  · ROUTES (register["routes"], in precedence order) name the item that owns an area — by file prefix or by a
    word in the row's title. `followups.py add` routes a row with no --slot; a HIGH row rides the next open
    item. A route pointing at a DONE item fails the check, so a finished item hands its area on.
  · PLAN NOW — a second generated block (next item, the order after it with each item's riders, done per
    phase, follow-up totals) replaces the hand-kept "NEXT —" line in WHERE THE PLAN STANDS and sits in the
    living plan's §6.4; `followups.py done P1.13 --by W470` marks an item done, moves its riders along the
    routes, and re-renders both docs in one locked write.

What check() enforces:
  · an open row slotted NEXT fails (retired, W469); a route that is malformed, names no plan item or points at a
    finished item fails;
  · an open row on a plan item marked "✅ DONE W###" (right after the item id) fails — the round closed
    without doing or re-slotting it; an item's first line that says done in any other form or place
    ("Done W470", a marker after the [ledger] bracket) fails too, so a mis-typed marker cannot keep rows
    "scheduled" on finished work ("DONE WHEN", the plan's acceptance idiom, is not a marker);
  · owner-gated work is slotted OWNER and nothing else; an unknown slot, a done row with no round, a
    dropped row with no reason and an open row with closed_by fail; a file an open row names must exist in
    the working tree AND be tracked by git (forward slashes, exact case) — the row has gone stale otherwise;
  · a malformed row is REPORTED and skipped, never raised, and never switches the other rules off;
  · each doc carries exactly one follow-up block and one PLAN NOW block, the prompt's inside the real
    <delivery_plan> section, and each equals its render — the docs cannot drift from the plan or the register.

CLI: scripts/followups.py (add · list · close · drop · reslot · route · routes · done · schedule · render · check).
"""
