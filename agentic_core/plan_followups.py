REPLACE_TRIES = 50            # × 20 ms: on Windows a reader holding the target makes os.replace fail briefly


def atomic_write(path: Path, data: bytes) -> None:
    """Temp file + os.replace, retried while another process holds the target. The temp never outlives a
    failure or an interrupt, and a failure names the TARGET it could not replace (not the temp)."""
    tmp = path.with_name(path.name + ".tmp")
    try:
        tmp.write_bytes(data)
        for attempt in range(REPLACE_TRIES):
            try:
                os.replace(tmp, path)
                return
            except PermissionError as exc:
                if attempt == REPLACE_TRIES - 1:
                    raise PermissionError(exc.errno, f"{path.name} is held open by another program", str(path)) from exc
                time.sleep(0.02)
    except BaseException:
        try:
            tmp.unlink()
        except OSError:
            pass
        raise


class PartialWrite(OSError):
    """write_all failed AND could not put every already-replaced file back: `unrestored` names them."""

    def __init__(self, cause: BaseException, unrestored: List[Path]):
        super().__init__(f"{cause}; not put back: {', '.join(p.name for p in unrestored)}")
        self.cause = cause
        self.unrestored = unrestored


def write_all(writes: List[Any]) -> None:
    """(path, old_bytes, new_bytes) in order, all or nothing: if a later write fails — or the run is
    interrupted — every file already replaced gets its old bytes back and the error is re-raised. If a
    restore itself fails, PartialWrite names the files still carrying the new bytes (render repairs the docs
    from the register, which is written last). A hard kill between two replaces is the one case this cannot
    cover; check reports it and render repairs it."""
    done: List[Any] = []
    try:
        for path, old, new in writes:
            if new != old:
                atomic_write(path, new)
                done.append((path, old))
    except BaseException as exc:
        unrestored: List[Path] = []
        for path, old in reversed(done):
            try:
                atomic_write(path, old)
            except OSError:
                unrestored.append(path)
        if unrestored:
            raise PartialWrite(exc, unrestored) from exc
        raise


def read_doc(path: Path) -> str:
    """Docs are read as bytes so a doc's own line endings survive a round trip (read_text would fold CRLF)."""
    return path.read_bytes().decode("utf-8")


def delivery_plan_body(prompt_text: str) -> Optional[str]:
    """The real <delivery_plan> section — the tag on a line of its own, not a prose mention of it."""
    m = re.search(r"^<delivery_plan>[ \t]*\r?$(.*?)^</delivery_plan>[ \t]*\r?$", prompt_text, flags=re.M | re.S)
    return m.group(1) if m else None


def _without_blocks(text: str) -> str:
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", text, flags=re.S)
    return re.sub(re.escape(PLAN_BEGIN) + r".*?" + re.escape(PLAN_END), "", text, flags=re.S)


def _item_blocks(body: str) -> Dict[str, str]:
    """Each delivery-plan item's whole text (its id line and the indented lines under it), keyed by slot."""
    blocks: Dict[str, str] = {}
    cur = None
    for line in _without_blocks(body).splitlines():
        m = re.match(r"^ (P\d+\.\d+)\b", line)
        if m:
            cur = m.group(1)
            blocks[cur] = line
        elif cur and (line.startswith("      ") or not line.strip()):
            blocks[cur] += "\n" + line
        else:
            cur = None
    return blocks


def plan_items(prompt_text: str) -> List[Dict[str, Any]]:
    """The delivery plan's items IN PLAN ORDER, each with its done state — read from the plan itself,
    so a newly added item or a new "✅ DONE W###" marker is seen without touching this module."""
    body = delivery_plan_body(prompt_text)
    if body is None:
        return []
    items = []
    for line in _without_blocks(body).splitlines():
        m = re.match(r"^ (P\d+\.\d+)\b(.*?)\r?$", line)
        if not m:
            continue
        rest = m.group(2).replace("️", "")           # a variation selector must not hide a marker
        done = _DONE.match(rest)                           # only right after the id — never a cross-reference
        title = _DONE.sub("", rest) if done else rest
        title = re.sub(r"^\s*\[[^\]]*\]\s*", "", title).strip()
        title = title.split(". ")[0].rstrip(".")          # the item's name: its first sentence
        items.append({"slot": m.group(1), "title": title[:110], "done": bool(done),
                      "done_by": done.group(1) if done else None,
                      # said done in any other form or place on the line: reported, never read as open
                      "malformed_done": (not done) and bool(_DONE_MENTION.search(rest))})
    return items


def _row_shape_problems(r: Any, idx: int) -> List[str]:
    if not isinstance(r, dict):
        return [f"row {idx}: not an object"]
    rid = r.get("id") if isinstance(r.get("id"), str) else f"row {idx}"
    missing = [k for k in REQUIRED if k not in r]
    if missing:
        return [f"{rid}: missing {', '.join(missing)}"]
    p: List[str] = []
    for k in TEXT_FIELDS:
        v = r[k]
        if not isinstance(v, str) or not v.strip():
            p.append(f"{rid}: {k} must be a non-empty string")
        elif "\r" in v or "\n" in v or any(m in v for m in (BEGIN, END, PLAN_BEGIN, PLAN_END)):
            p.append(f"{rid}: {k} must be one line (no line breaks or markers)")
    if not isinstance(r["owner_gated"], bool):
        p.append(f"{rid}: owner_gated must be true or false (not {r['owner_gated']!r})")
    if not isinstance(r["files"], list) or not all(isinstance(f, str) and f.strip() for f in r["files"]):
        p.append(f"{rid}: files must be a list of repository paths")
    if r["severity"] not in SEVERITIES:
        p.append(f"{rid}: severity must be one of {SEVERITIES}")
    if r["status"] not in STATUSES:
        p.append(f"{rid}: status must be one of {STATUSES}")
    for k in ("closed_by", "note"):
        if k in r and r[k] is not None and not isinstance(r[k], str):
            p.append(f"{rid}: {k} must be a string or null")
    return p


def raw_items(register: Any) -> List[Any]:
    items = register.get("items") if isinstance(register, dict) else None
    return items if isinstance(items, list) else []


def _rows(register: Any) -> List[Dict[str, Any]]:
    """The well-formed rows only — everything that renders or schedules reads these, so a malformed row is
    reported by check() and can never crash a renderer or reach a page as an object."""
    return [r for i, r in enumerate(raw_items(register)) if not _row_shape_problems(r, i)]


def id_number(value: Any) -> Optional[int]:
    """Lenient: 'FU-14', 'fu-014 ' and 'FU-014' are all 14 — used for numbering and duplicate detection."""
    m = re.search(r"(\d+)", str(value))
    return int(m.group(1)) if m else None


def _num(r: Dict[str, Any]) -> int:
    m = _ID.match(str(r.get("id", "")))
    return int(m.group(1)) if m else 10 ** 9


def _ordered(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    # severity first, then the order they were found (the register is append-only; ids compared as numbers)
    return sorted(rows, key=lambda r: (_SEV_RANK.get(str(r.get("severity")), 9), _num(r)))


def _open_items(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen: Set[str] = set()
    out = []
    for it in items:
        if it["done"] or it["slot"] in seen:
            continue
        seen.add(it["slot"])
        out.append(it)
    return out


def _gate_phase(open_items: List[Dict[str, Any]]) -> Optional[str]:
    return open_items[0]["slot"].split(".")[0] if open_items else None


def _prioritised(rows: List[Dict[str, Any]], cfg: Dict[str, Any], gate: Optional[str]) -> List[Dict[str, Any]]:
    """W478 — each row a COPY carrying its priority (score, parts, basis); highest first, the old order breaking ties."""
    from agentic_core import plan_priority as pp
    out = [dict(r, priority=pp.score_row(r, cfg, gate)) for r in rows]
    return sorted(out, key=lambda r: (-r["priority"]["score"], _SEV_RANK.get(str(r.get("severity")), 9), _num(r)))


def schedule(register: Dict[str, Any], prompt_text: str) -> Dict[str, Any]:
    from agentic_core import plan_priority as pp
    items = plan_items(prompt_text)
    rows = _rows(register)
    open_rows = [r for r in rows if r["status"] == "open"]
    riders = [r for r in open_rows if r["owner_gated"] is not True]
    open_items = _open_items(items)
    first_open = open_items[0]["slot"] if open_items else None
    cfg, cfg_problems = pp.load_config(ROOT)
    gate = _gate_phase(open_items)
    slots: List[Dict[str, Any]] = []
    for it in open_items:
        # W478 — inside an item the rows run highest-priority first (the plan's item order and phase gates stand)
        slotted = _prioritised([r for r in riders if r["slot"] == it["slot"]], cfg, gate)
        if slotted:
            slots.append({"slot": it["slot"], "title": it["title"], "items": slotted,
                          "open_priority": round(sum(r["priority"]["score"] for r in slotted), 1)})
    # W469 — a row that rides no open plan item (the retired NEXT, an unknown slot, a finished item) is shown, never
    # silently left out of the schedule; check() names what to do with it
    open_slots = {it["slot"] for it in open_items}
    # a plan with no readable items classifies nothing: every row is not 'unscheduled' because the plan is unreadable
    unscheduled = _ordered([r for r in riders if r["slot"] not in open_slots]) if items else []
    closed = [r for r in rows if r["status"] != "open"]
    return {
        "counts": {
            "open": len(open_rows),
            "scheduled": sum(len(s["items"]) for s in slots),
            "unscheduled": len(unscheduled),
            "high": sum(1 for s_ in slots for r in s_["items"] if r["severity"] == "high"),
            "awaiting_owner": sum(1 for r in open_rows if r["owner_gated"] is True),
            "done": sum(1 for r in closed if r["status"] == "done"),
            "dropped": sum(1 for r in closed if r["status"] == "dropped"),
        },
        "next_plan_item": first_open,
        "schedule": slots,
        "unscheduled": unscheduled,
        "awaiting_owner": _ordered([r for r in open_rows if r["owner_gated"] is True]),
        "closed": closed,
        # W478 — the priority in force: completion weighted by what the rows are worth, and the open items by total
        # open priority for the Owner to consider beside the plan's own order (never applied automatically)
        "priority": {
            "gate_phase": gate,
            "config": "docs/PRIORITY.json" if pp.config_path(ROOT).exists() else "built-in defaults (no docs/PRIORITY.json)",
            "config_problems": cfg_problems,
            "completion": pp.completion(rows, cfg, gate),
            "suggested_order": [s_["slot"] for s_ in sorted(slots, key=lambda s_: -s_["open_priority"])],
        },
    }


# ── W469 — routes: which plan item owns an area, so a found task rides the plan instead of queueing before it ──
def raw_routes(register: Any) -> List[Any]:
    routes = register.get("routes") if isinstance(register, dict) else None
    return routes if isinstance(routes, list) else []


def _route_shape_problems(rt: Any, idx: int) -> List[str]:
    name = f"route {idx + 1}"
    if not isinstance(rt, dict):
        return [f"{name}: not an object"]
    p: List[str] = []
    slot = rt.get("slot")
    if not isinstance(slot, str) or not _ITEM_SLOT.match(slot):
        p.append(f"{name}: slot must name a delivery-plan item like P2.9 (not {slot!r})")
    for key in ("files", "words"):
        v = rt.get(key, [])
        if not isinstance(v, list) or not all(isinstance(x, str) and x.strip() for x in v):
            p.append(f"{name}: {key} must be a list of non-empty strings")
    if not p:
        if not rt.get("files") and not rt.get("words"):
            p.append(f"{name} ({slot}): needs at least one file prefix or title word to match")
        bad = [f for f in rt.get("files", []) if f != normalise_path(f) or f.startswith("/") or re.match(r"^[A-Za-z]:", f)]
        if bad:
            p.append(f"{name} ({slot}): file prefix {bad[0]!r} must be repository-relative with forward slashes")
        if any(w != w.strip().lower() for w in rt.get("words", [])):
            p.append(f"{name} ({slot}): title words are matched in lower case — write them in lower case")
    if "note" in rt and not isinstance(rt["note"], str):
        p.append(f"{name}: note must be a string")
    if "handed_from" in rt:
        hf = rt["handed_from"]
        if not (isinstance(hf, str) and _ITEM_SLOT.match(hf)):
            p.append(f"{name} ({slot}): handed_from must name a plan item (P#.#)")
        elif hf == slot:
            p.append(f"{name} ({slot}): handed_from names the route's own item")
    return p


def merge_routes(register: Dict[str, Any], from_slot: str, to_slot: str) -> int:
    """W469 (refutation) — hand an item's area to another. W473 (register FU-073): the handed route KEEPS ITS PLACE
    and only its slot changes — it becomes a second route to `to_slot` marked `handed_from`, so the handed area keeps
    exactly the precedence it had and the taker's own matchers stay where they were (the W469 merge moved the taker's
    broad prefixes to the handed route's position: done P1.13 --hand-to P1.16 lifted docs/ and integration_tests/ to
    the first route). (Refutation) EVERY moving route is handed in its own place — nothing is ever joined; a route
    handed on again keeps `handed_from` = the item it first belonged to and its note says `via`. A malformed route is
    never merged (its string would be read letter by letter), and a route that was itself handed from `to_slot` is
    never handed back to it (it would name its own item): ValueError, repair it first. Returns how many routes were
    handed (0: nothing to hand)."""
    routes = register.setdefault("routes", [])
    if not isinstance(routes, list):
        raise ValueError("the register's routes are not a list — repair it by hand first")
    moving = [rt for rt in routes if isinstance(rt, dict) and rt.get("slot") == from_slot]
    handed = len(moving)
    if not moving:
        return 0
    for rt in moving:
        shape = _route_shape_problems(rt, routes.index(rt))
        if shape:
            raise ValueError(f"{shape[0]} — repair that route before handing its area on")
        if rt.get("handed_from") == to_slot:
            raise ValueError(f"the route to {from_slot} was handed from {to_slot}; it cannot go back to it — remove it "
                             f"(python scripts/followups.py route --slot {from_slot} --remove --handed) or hand it elsewhere")
    for rt in moving:                                  # (refutation) each route keeps its own place and its origin
        rt["slot"] = to_slot
        origin = rt.get("handed_from") or from_slot    # a route handed on again keeps the item it first belonged to
        rt["handed_from"] = origin
        rt["note"] = "; ".join(dict.fromkeys(n for n in (f"handed from {origin} via {from_slot}" if origin != from_slot
                                                        else f"handed from {from_slot}", rt.get("note")) if n))
    return handed


def _routes(register: Any) -> List[Dict[str, Any]]:
    return [rt for i, rt in enumerate(raw_routes(register)) if not _route_shape_problems(rt, i)]


def _route_matches(rt: Dict[str, Any], title: str, files: List[str]) -> Optional[str]:
    """How the route matches a row — a file under one of its prefixes, or one of its words in the row's title (whole
    words, lower case) — or None."""
    for f in files:
        for prefix in rt.get("files", []):
            if f == prefix or (prefix.endswith("/") and f.startswith(prefix)):
                return f"file {f} (route {rt['slot']}: {prefix})"
    low = title.lower()
    for w in rt.get("words", []):
        if re.search(r"(?<![a-z0-9_])" + re.escape(w) + r"(?![a-z0-9_])", low):
            return f"title word '{w}' (route {rt['slot']})"
    return None


def route_row(register: Any, prompt_text: str, title: str, files: List[str], severity: str,
              exclude: Optional[Set[str]] = None) -> Dict[str, Any]:
    """The plan item a new or moved row rides: a HIGH row rides the next open item (it must not wait for its area's
    turn); otherwise the first route (in the register's order) that matches and points at an open item. A route
    pointing at a finished item is skipped here (check() reports it). {slot: None, reason} when nothing matches."""
    exclude = exclude or set()
    open_items = [it for it in _open_items(plan_items(prompt_text)) if it["slot"] not in exclude]
    open_slots = {it["slot"] for it in open_items}
    if severity == "high":
        if open_items:
            return {"slot": open_items[0]["slot"], "by": "high severity rides the next open plan item"}
        return {"slot": None, "reason": "a high-severity row rides the next open plan item, and none is open"}
    for rt in _routes(register):
        if rt["slot"] not in open_slots:
            continue
        how = _route_matches(rt, title, [normalise_path(f) for f in files])
        if how:
            return {"slot": rt["slot"], "by": how}
    return {"slot": None,
            "reason": "no route matches its files or title — name the plan item with --slot (or add a route: "
                      "python scripts/followups.py route --slot P… --files … --words …)"}


# ── W469 — PLAN NOW: the plan's live state, generated, so no hand-kept line can go stale ──
def plan_now(register: Any, prompt_text: str) -> Dict[str, Any]:
    items = plan_items(prompt_text)
    s = schedule(register if isinstance(register, dict) else {"items": []}, prompt_text)
    riding = {x["slot"]: x["items"] for x in s["schedule"]}
    phases: List[Dict[str, Any]] = []
    for it in items:
        ph = it["slot"].split(".")[0]
        if not phases or phases[-1]["phase"] != ph:
            phases.append({"phase": ph, "done": 0, "total": 0})
        phases[-1]["total"] += 1
        phases[-1]["done"] += 1 if it["done"] else 0
    open_items = [{"slot": it["slot"], "title": it["title"],
                   "followups": len(riding.get(it["slot"], [])),
                   "by_severity": {sev: sum(1 for r in riding.get(it["slot"], []) if r["severity"] == sev)
                                   for sev in SEVERITIES},
                   # W478 — the rows' total open priority, and the highest-priority rows first
                   "open_priority": round(sum(r["priority"]["score"] for r in riding.get(it["slot"], [])), 1),
                   "top": [{"id": r["id"], "score": r["priority"]["score"], "area": r["priority"]["area"],
                            "tier": r["priority"]["tier"]} for r in riding.get(it["slot"], [])[:5]]}
                  for it in _open_items(items)]
    return {"readable": bool(items),
            "next": open_items[0] if open_items else None, "open_items": open_items, "phases": phases,
            "done": sum(p["done"] for p in phases), "total": sum(p["total"] for p in phases),
            "followups": s["counts"], "unscheduled": [r["id"] for r in s["unscheduled"]],
            "priority": s["priority"]}



# ── W486: the pace the plan is actually moving at ────────────────────────────
# The Owner asked to be able to see where this is going without asking. Everything below is
# MEASURED from the register itself — which round closed each row (`closed_by`) and which round
# found it (the `W###` in `source`/`found`) — and the projection is stated in ROUNDS, because a
# round is the unit the register can count. It does not know how long a round takes; the CLI adds
# that separately from git, and says so.
#
# The honesty rules this obeys, which are the whole point of it:
#   · a rate measured over fewer than MIN_OBSERVED build rounds is `not assessable`, not a guess;
#   · if the backlog is NOT shrinking (rows found per round >= rows closed per round) no completion
#     is projected at all — the answer is "not at this rate", with the two numbers shown;
#   · the projection is arithmetic over an observed mean, and it says so in `basis`. It is not a
#     promise, a deadline, or a date.
FORECAST_WINDOW = 6          # the most recent build rounds the rate is measured over
MIN_OBSERVED = 3             # fewer than this and the rate is not assessable


def _round_activity(register: Any) -> Dict[str, Dict[str, int]]:
    """{round_id: {closed, found}} from the register's own record of each row."""
    import re as _re
    act: Dict[str, Dict[str, int]] = {}

    def _slot(rid: str) -> Dict[str, int]:
        return act.setdefault(rid, {"closed": 0, "found": 0})

    for r in raw_items(register):
        if not isinstance(r, dict):
            continue
        by = str(r.get("closed_by") or "").strip()
        if by and _re.fullmatch(r"W\d{3}", by):
            _slot(by)["closed"] += 1
        m = _re.search(r"\bW(\d{3})\b", f"{r.get('source') or ''} {r.get('found') or ''}")
        if m:
            _slot("W" + m.group(1))["found"] += 1
    return act


def _item_activity(register: Any) -> Dict[str, Dict[str, int]]:
    """{slot: {round_id: rows closed}} - the closure record PER PLAN ITEM.

    W493 (the C4/C10 rule turned on the planner itself): the projection for a single item divided THAT
    item's open rows by the rate measured over the WHOLE register, so the figure was arithmetic over a
    population the label did not name. The gate P1.18 read "35 open rows ~ 4 rounds" while the same
    six-round window this rate uses closed 16 of its rows - 2.67 per round, about fourteen rounds. A
    class-wide batch closes rows across five or six items at once, so the overall rate is three to five
    times any single item's. An item is projected at ITS OWN rate or it is not projected.

    Both numbers are measured over the SAME window as the overall rate, so the two are comparable; a
    figure quoted over a different span of rounds would repeat the defect in the fix's own notes."""
    import re as _re
    per: Dict[str, Dict[str, int]] = {}
    for r in raw_items(register):
        if not isinstance(r, dict):
            continue
        by = str(r.get("closed_by") or "").strip()
        if not (by and _re.fullmatch(r"W\d{3}", by)):
            continue
        # a closed row keeps the item it rode in `slot`; `item` is cleared when it closes
        slot = str(r.get("slot") or r.get("item") or "").strip()
        if not slot:
            continue
        per.setdefault(slot, {})
        per[slot][by] = per[slot].get(by, 0) + 1
    return per


def forecast(register: Any, prompt_text: str, window: int = FORECAST_WINDOW) -> Dict[str, Any]:
    """What the plan's own record says about its pace, and what that projects — or why it cannot."""
    items = plan_items(prompt_text)
    s = schedule(register if isinstance(register, dict) else {"items": []}, prompt_text)
    riding = {x["slot"]: x["items"] for x in s["schedule"]}
    act = _round_activity(register)

    # A BUILD round is one that closed at least one row. Rounds that only registered findings (a
    # sweep, an interrogation) are counted as what they were — they add work, they do not burn it.
    build = sorted([r for r, a in act.items() if a["closed"] > 0])
    recent = build[-window:]
    closed = [act[r]["closed"] for r in recent]
    found = [act[r]["found"] for r in recent]
    n = len(recent)
    per_round_closed = round(sum(closed) / n, 2) if n else 0.0
    per_round_found = round(sum(found) / n, 2) if n else 0.0
    net = round(per_round_closed - per_round_found, 2)

    # A ONE-TIME INTAKE is a round that registered findings far beyond the usual — an audit, a sweep,
    # an interrogation of an outside proposal. W477 alone registered 100 rows. Averaging that into an
    # ongoing rate says the backlog grows forever, which is as untrue as ignoring it. Both numbers are
    # reported, the excluded rounds are NAMED, and neither is presented as the real one on its own.
    _med = sorted(found)[n // 2] if n else 0
    _spikes = [r for r in recent if act[r]["found"] > max(3 * _med, 10)]
    steady = [r for r in recent if r not in _spikes]
    sn = len(steady)
    steady_closed = round(sum(act[r]["closed"] for r in steady) / sn, 2) if sn else 0.0
    steady_found = round(sum(act[r]["found"] for r in steady) / sn, 2) if sn else 0.0
    steady_net = round(steady_closed - steady_found, 2)

    open_rows = [r for slot in s["schedule"] for r in slot["items"]]
    open_items = _open_items(items)
    nxt = open_items[0] if open_items else None
    next_open = len(riding.get(nxt["slot"], [])) if nxt else 0

    # The projection uses the STEADY rate (one-time intakes excluded) and says so; with none
    # excluded the two are the same number.
    _rate, _rnet, _rn = (steady_closed, steady_net, sn) if sn >= MIN_OBSERVED else (per_round_closed, net, n)

    def _rounds_for(rows: int) -> Optional[int]:
        if _rn < MIN_OBSERVED or _rate <= 0 or _rnet <= 0:
            return None
        import math as _math
        return int(_math.ceil(rows / _rate))

    # W493 - an ITEM is projected at the rate measured on ITS OWN rows, over the same window of rounds
    # that closed anything. Dividing one item's backlog by the whole register's rate is a projection
    # about a population the label does not name: it made the current gate read four rounds when its
    # own record says eighteen. Too little history on an item means NO number, never a borrowed one.
    _per_item = _item_activity(register)

    def _item_rate(slot: str) -> Dict[str, Any]:
        rec = _per_item.get(slot) or {}
        mine = [rec.get(r, 0) for r in recent]          # the same rounds the overall rate uses
        rounds_closing = [r for r in recent if rec.get(r, 0) > 0]
        n_mine = len(rounds_closing)
        rate = round(sum(mine) / len(recent), 2) if recent else 0.0
        return {"rate": rate, "rounds_closing": rounds_closing, "closed_in_window": sum(mine),
                "assessable": bool(n_mine >= MIN_OBSERVED and rate > 0)}

    def _item_projection(slot: str, rows: int) -> Dict[str, Any]:
        ir = _item_rate(slot)
        if rows <= 0:
            return {"rounds_projected": 0, "rate_used": ir["rate"],
                    "basis": "no open row rides this item"}
        if not ir["assessable"]:
            return {"rounds_projected": None, "rate_used": ir["rate"],
                    "basis": (f"not projected: only {len(ir['rounds_closing'])} of the last "
                              f"{len(recent)} build round(s) closed a row on {slot} "
                              f"(a rate needs {MIN_OBSERVED}); the overall rate is measured over "
                              f"every item's rows and is not this item's")}
        import math as _math
        return {"rounds_projected": int(_math.ceil(rows / ir["rate"])),
                "rate_used": ir["rate"],
                "basis": (f"at {slot}'s OWN rate: {ir['closed_in_window']} row(s) over the last "
                          f"{len(recent)} build round(s) = {ir['rate']}/round")}

    assessable = _rn >= MIN_OBSERVED and _rate > 0
    if not assessable:
        why = (f"only {n} build round(s) on record — a rate needs at least {MIN_OBSERVED}"
               if n < MIN_OBSERVED else "no round on record has closed a row")
    elif _rnet <= 0:
        why = (f"the backlog is not shrinking: the last {_rn} build rounds closed {_rate} rows each "
               f"and registered {steady_found if sn >= MIN_OBSERVED else per_round_found}, a net of "
               f"{_rnet} per round. No completion is projected at this rate")
    else:
        why = None

    return {
        "assessable": bool(assessable and _rnet > 0),
        "not_assessable_because": why,
        "window": {"rounds": recent, "count": n,
                   "closed_per_round": per_round_closed, "found_per_round": per_round_found,
                   "net_per_round": net},
        # the same window with one-time intakes (audits, sweeps, interrogations) taken out and named
        "steady": {"rounds": steady, "count": sn, "excluded": _spikes,
                   "closed_per_round": steady_closed, "found_per_round": steady_found,
                   "net_per_round": steady_net},
        "rate_used": {"closed_per_round": _rate, "net_per_round": _rnet, "rounds": _rn,
                      "source": ("steady (one-time intakes excluded)" if sn >= MIN_OBSERVED
                                 else "the whole window")},
        "open_rows": len(open_rows),
        "next_item": (None if not nxt else dict(
            {"slot": nxt["slot"], "title": nxt["title"], "open_rows": next_open},
            **_item_projection(nxt["slot"], next_open))),
        "by_item": [dict({"slot": it["slot"], "open_rows": len(riding.get(it["slot"], []))},
                         **_item_projection(it["slot"], len(riding.get(it["slot"], []))))
                    for it in open_items],
        "items": {"done": sum(1 for i in items if i["done"]), "total": len(items),
                  "open": len(open_items)},
        "all_rows_rounds_projected": _rounds_for(len(open_rows)),
        "basis": ("measured from the register: which round closed each row and which round found it. "
                  f"The rate is the mean over the last {n} round(s) that closed anything, ACROSS EVERY "
                  "ITEM - a class-wide batch closes rows on five or six items at once, so no single "
                  "item moves at this rate. ALL OPEN ROWS uses it because it covers the same "
                  "population; each ITEM is projected at the rate measured on its own rows, or not "
                  "projected at all. A projection "
                  "is arithmetic over that mean, in ROUNDS — the register does not record how long a "
                  "round takes, and this is not a date, a deadline or a promise. Rounds that only "
                  "registered findings are counted as finding work, never as burning it."),
    }


